function batches(arr, size) {
  const result = [];
  for (let i = 0; i < arr.length; i += size) {
    result.push(arr.slice(i, i + size));
  }
  return result;
}

function insertSQL(bookVar, words) {
  const rows = words.map(w => {
    const meaning = w;
    const audio = `https://dict.youdao.com/dictvoice?audio=${w}&type=2`;
    return `(${bookVar}, '${escape(w)}', '${escape(meaning)}', '${escape(audio)}')`;
  });
  return 'INSERT IGNORE INTO words (book_id, word, meaning, audio_url) VALUES\n  ' + rows.join(',\n  ') + ';';
}

